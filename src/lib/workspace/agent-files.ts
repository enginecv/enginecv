/** First line of generated files, so a file the person edited is never overwritten (research R11). */
export const GENERATED_MARK = "<!-- generated by EngineCV; edit freely, EngineCV will not overwrite a changed copy -->";

function agentsBody(): string {
    return `${GENERATED_MARK}
# EngineCV workspace

This folder mirrors EngineCV CVs and cover letters as plain JSON files. EngineCV (open in a browser tab) reads every change you save here.

Start with \`.enginecv/index.json\`, then open only the file you need.
- CVs: \`cvs/*.cv.json\`
- Letters: \`letters/*.letter.json\`

Rules
1. Change only what was asked. Keep \`id\`, \`format\` and every entry you were not asked to touch.
2. Save the whole file in one write. Never leave it half written.
3. Do not remove many entries or whole sections unless told to. EngineCV holds such a change for review.
4. A letter with \`"status": "sent"\` is frozen. To reuse it, write a new letter file with a new \`id\`.
5. Do not edit \`exports/\` or \`.enginecv/\`, except request files.
6. If EngineCV refuses a change, read \`.enginecv/results/\` and \`.enginecv/log.ndjson\`, fix the file and save again.

Read more only when needed
- \`.enginecv/reference/cv-format.md\`: CV fields
- \`.enginecv/reference/letter-format.md\`: letters
- \`.enginecv/reference/exports.md\`: exports and PDFs
- \`.enginecv/reference/recipes.md\`: worked examples
`;
}

/** The generated-file header: the mark, then a hash of the body, so an edit by the person can be told from an out-of-date copy. */
export function stamped(text: string): string {
    const [mark, ...rest] = text.split("\n");
    const body = rest.join("\n");
    return `${mark}\n<!-- hash:${hashText(body)} -->\n${body}`;
}

/** True when a generated file still has the text EngineCV wrote (an edit changes the body, not the stored hash). */
export function isUntouched(text: string): boolean {
    const lines = text.split("\n");
    if (lines[0] !== GENERATED_MARK) return false;
    const match = /^<!-- hash:([0-9a-f]+:[0-9]+) -->$/.exec(lines[1] ?? "");
    return !!match && match[1] === hashText(lines.slice(2).join("\n"));
}

