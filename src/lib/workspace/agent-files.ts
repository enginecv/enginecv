function readmeBody(): string {
    return `${GENERATED_MARK}
# EngineCV workspace folder

EngineCV keeps your CVs and cover letters in this folder as readable files, so you can back them up, put them under version control or let an AI agent edit them.

- \`cvs/\` one file per CV, \`letters/\` one file per cover letter
- \`exports/\` files EngineCV writes when asked (PDF, Word and so on)
- \`.enginecv/\` machine files EngineCV maintains; \`.enginecv/.gitignore\` keeps the noisy ones out of git
- \`AGENTS.md\` the short instructions an agent reads first

These files contain your personal details (name, email, phone, address) unless you chose to leave contact details out. If this folder is in a repository or a cloud folder, those services can see them.

The files stay on your computer. EngineCV never uploads them.
`;
}

export function workspaceJson(input: { id: string; createdAt: number; appVersion: string; hideContact: boolean }): string {
    return `${JSON.stringify({ format: WORKSPACE_FORMAT, id: input.id, createdAt: new Date(input.createdAt).toISOString(), appVersion: input.appVersion, hideContact: input.hideContact }, null, 2)}\n`;
}

/** Keeps the machine area's transient files out of version control (the setup also writes this file). */
export function machineGitignore(): string {
    return "requests/\nresults/\nconflicts/\nlog.ndjson\n";
}

