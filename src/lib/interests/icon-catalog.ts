const BY_NAME: ReadonlyMap<string, InterestIconEntry> = new Map(INTEREST_ICONS.map((entry) => [entry.name, entry]));

export function getInterestIcon(name: string): InterestIconEntry | undefined {
    return BY_NAME.get(name);
}

/**
 * Case-insensitive search over name, label and keywords. An empty query returns
 * the whole catalog. Results where the query matches the start of the name or
 * a keyword come first.
 */
export function searchInterestIcons(query: string): readonly InterestIconEntry[] {
    const q = query.trim().toLowerCase();
    if (!q) return INTEREST_ICONS;
    const scored: Array<{ entry: InterestIconEntry; score: number }> = [];
    for (const entry of INTEREST_ICONS) {
        const haystacks = [entry.name, entry.label.toLowerCase(), ...entry.keywords];
        let score = -1;
        for (const text of haystacks) {
            if (text === q) score = Math.max(score, 3);
            else if (text.startsWith(q)) score = Math.max(score, 2);
            else if (text.includes(q)) score = Math.max(score, 1);
        }
        if (score > 0) scored.push({ entry, score });
    }
    return scored.sort((a, b) => b.score - a.score).map((item) => item.entry);
}
