const DOT_DATE_LANGUAGES = new Set([
    "bs", "de", "hr", "sr", "sl", "cs", "sk", "pl", "ro", "hu", "fi", "sv", "no", "da",
]);

export function getDefaultCvDateFormat(language: string): string {
    const normalized = language.toLowerCase();
    if (normalized === "en" || normalized === "en-us") return "MM/DD/YYYY";
    if (DOT_DATE_LANGUAGES.has(normalized.split("-")[0])) return "DD.MM.YYYY";
    return "DD/MM/YYYY";
}

function buildCvDateTranslations(locale: string): CvDateTranslationSet {
    const monday = new Date(2026, 0, 5);
    return {
        months: {
            short: Array.from({ length: 12 }, (_, index) => (
                new Intl.DateTimeFormat(locale, { month: "short" }).format(new Date(2026, index, 1))
            )),
            long: Array.from({ length: 12 }, (_, index) => (
                new Intl.DateTimeFormat(locale, { month: "long" }).format(new Date(2026, index, 1))
            )),
        },
        weekdays: {
            short: Array.from({ length: 7 }, (_, index) => (
                new Intl.DateTimeFormat(locale, { weekday: "short" }).format(
                    new Date(monday.getFullYear(), monday.getMonth(), monday.getDate() + index)
                )
            )),
            long: Array.from({ length: 7 }, (_, index) => (
                new Intl.DateTimeFormat(locale, { weekday: "long" }).format(
                    new Date(monday.getFullYear(), monday.getMonth(), monday.getDate() + index)
                )
            )),
        },
    };
}

const CV_DATE_TRANSLATIONS: Record<string, CvDateTranslationSet> = Object.fromEntries(
    Object.entries(CV_LANGUAGE_LABELS).map(([language, labels]) => [
        language,
        CV_DATE_TRANSLATION_OVERRIDES[language] || buildCvDateTranslations(labels.locale),
    ])
) as Record<string, CvDateTranslationSet>;

export function getCvLanguageLabels(language: string) {
    const baseLanguage = language.split("-")[0];
    const resolvedLanguage = CV_LANGUAGE_LABELS[language]
        ? language
        : CV_LANGUAGE_LABELS[baseLanguage]
            ? baseLanguage
            : "en";
    const documentLabels = CV_DOCUMENT_LABELS[resolvedLanguage]
        || CV_DOCUMENT_LABELS[baseLanguage]
        || CV_DOCUMENT_LABELS.en;

    return {
        ...CV_LANGUAGE_LABELS[resolvedLanguage],
        ...documentLabels,
    };
}

function getCvLocale(language: string) {
    return getCvLanguageLabels(language).locale;
}

export function getCvMonthNames(language: string, width: "short" | "long") {
    if (CV_DATE_TRANSLATIONS[language]) {
        return CV_DATE_TRANSLATIONS[language].months[width];
    }

    const baseLanguage = language.split("-")[0];
    if (CV_DATE_TRANSLATIONS[baseLanguage]) {
        return CV_DATE_TRANSLATIONS[baseLanguage].months[width];
    }

    return CV_DATE_TRANSLATIONS.en.months[width];
}

export function getCvWeekdayNames(language: string, width: "short" | "long" = "short") {
    if (CV_DATE_TRANSLATIONS[language]) {
        return CV_DATE_TRANSLATIONS[language].weekdays[width];
    }

    const baseLanguage = language.split("-")[0];
    if (CV_DATE_TRANSLATIONS[baseLanguage]) {
        return CV_DATE_TRANSLATIONS[baseLanguage].weekdays[width];
    }

    return CV_DATE_TRANSLATIONS.en.weekdays[width];
}

function formatEnglishOrdinal(day: number) {
    const mod10 = day % 10;
    const mod100 = day % 100;
    if (mod10 === 1 && mod100 !== 11) return `${day}st`;
    if (mod10 === 2 && mod100 !== 12) return `${day}nd`;
    if (mod10 === 3 && mod100 !== 13) return `${day}rd`;
    return `${day}th`;
}

function toDateParts(value: string): { year: number; month: number; day: number } | null {
    if (!value || value === "Present") return null;
    if (/^\d{4}-\d{2}-\d{2}$/.test(value)) {
        const [year, month, day] = value.split("-").map(Number);
        return { year, month, day };
    }
    if (/^\d{2}\/\d{4}$/.test(value)) {
        const [month, year] = value.split("/").map(Number);
        return { year, month, day: 1 };
    }
    if (/^\d{4}-\d{2}$/.test(value)) {
        const [year, month] = value.split("-").map(Number);
        return { year, month, day: 1 };
    }
    if (/^\d{4}$/.test(value)) {
        return { year: Number(value), month: 1, day: 1 };
    }
    return null;
}

export function formatCvText(template: string, params?: Record<string, string | number>) {
    if (!params) {
        return template;
    }

    return Object.entries(params).reduce((text, [key, value]) => (
        text.replace(`{${key}}`, String(value))
    ), template);
}

export function formatCvDate(value: string, dateFormat = "DD/MM/YYYY", language = "en") {
    if (value === "Present") {
        return getCvLanguageLabels(language).present;
    }

    const parts = toDateParts(value);
    if (!parts) {
        return value;
    }

    const isYearOnly = /^\d{4}$/.test(value);
    const isMonthYearOnly = /^\d{2}\/\d{4}$/.test(value) || /^\d{4}-\d{2}$/.test(value);
    const locale = getCvLocale(language);
    const monthIndex = parts.month - 1;
    const monthShort = getCvMonthNames(language, "short")[monthIndex];
    const monthLong = getCvMonthNames(language, "long")[monthIndex];
    const dd = `${parts.day}`.padStart(2, "0");
    const day = `${parts.day}`;
    const mm = `${parts.month}`.padStart(2, "0");
    const yyyy = `${parts.year}`;
    const ordinalDay = locale.startsWith("en") ? formatEnglishOrdinal(parts.day) : day;

    if (isYearOnly) {
        return yyyy;
    }

    if (isMonthYearOnly) {
        if (dateFormat === "YYYY-MM-DD") return `${yyyy}-${mm}`;
        if (dateFormat === "DD.MM.YYYY") return `${mm}.${yyyy}`;
        if (dateFormat === "MMM DD, YYYY" || dateFormat === "DD MMM YYYY") return `${monthShort} ${yyyy}`;
        if (dateFormat === "MMMM Do, YYYY" || dateFormat === "Do MMMM YYYY") return `${monthLong} ${yyyy}`;
        return `${mm}/${yyyy}`;
    }

    if (dateFormat === "MM/DD/YYYY") return `${mm}/${dd}/${yyyy}`;
    if (dateFormat === "MMM DD, YYYY") return `${monthShort} ${dd}, ${yyyy}`;
    if (dateFormat === "MMMM Do, YYYY") return `${monthLong} ${ordinalDay}, ${yyyy}`;
    if (dateFormat === "DD.MM.YYYY") return `${dd}.${mm}.${yyyy}`;
    if (dateFormat === "DD MMM YYYY") return `${dd} ${monthShort} ${yyyy}`;
    if (dateFormat === "Do MMMM YYYY") return `${ordinalDay} ${monthLong} ${yyyy}`;
    if (dateFormat === "YYYY-MM-DD") return `${yyyy}-${mm}-${dd}`;
    return `${dd}/${mm}/${yyyy}`;
}
