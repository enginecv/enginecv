// Self-hosted resume fonts (OFL-1.1, via @fontsource). The files are bundled and
// served from EngineCV itself, so rendering a preview or exporting PNG/SVG never
// contacts a third-party font host. Each family registers under its plain name
// ("Inter", not "Inter Variable"), which is what resume settings store.
//
// Every family here is a preset in `src/lib/fonts.ts` and ships each weight its
// package provides, upright and italic where the family has italics, so the
// weight picker and the italic button never fall back to synthesized faces.
// A browser downloads a face only when a resume uses it.

